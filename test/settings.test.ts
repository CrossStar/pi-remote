import './isolate.ts';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { configPath, loadSettings, saveSettings, validate, readToken } from '../extensions/settings.ts';
import push from '../extensions/pi-remote.ts';
import type { ExtensionAPI } from '@earendil-works/pi-coding-agent';
test('private atomic settings, validation and startup/setup', async () => {
  assert.equal(loadSettings(), undefined);
  for (const value of [null, {}, {url:'https://a:b@example.test',topic:'ok'}, {url:'https://example.test',topic:'../bad'}, {url:'https://example.test',topic:'ok',enabled:'yes'}]) assert.throws(() => validate(value));
  const settings = {url:'https://example.test',topic:'ok',enabled:true};
  saveSettings(settings);
  assert.deepEqual(loadSettings(), settings);
  assert.equal(statSync(configPath()).mode & 0o777, 0o600);
  assert.equal(statSync(dirname(configPath())).mode & 0o777, 0o700);
  const tokenFile = join(dirname(configPath()), 'test-token');
  writeFileSync(tokenFile, 'fake-token', {mode:0o600});
  assert.equal(readToken(tokenFile), 'fake-token');
  let handler: Function = () => {};
  push({on() {}, registerCommand(_name: string, def: {handler:Function}) {handler = def.handler;} } as unknown as ExtensionAPI);
  const messages: string[] = [];
  const answers = [settings.url, 'changed', tokenFile];
  const ctx = {hasUI:true,ui:{input:async()=>answers.shift(),notify:(s:string)=>messages.push(s)}};
  await handler('status',ctx); assert.match(messages.at(-1)!, /configured=true/);
  await handler('setup',ctx); assert.equal(loadSettings()?.topic,'changed');
  assert.ok(!messages.join('').includes('fake-token'));
  await handler('setup',ctx); assert.equal(loadSettings()?.topic,'changed');
  writeFileSync(configPath(), '{broken');
  assert.throws(()=>loadSettings(), /Cannot load/);
});
